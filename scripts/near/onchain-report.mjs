// Writes docs/redteam/ONCHAIN.md from the evidence files the NEAR sandbox tests and mutation checks
// produce (docs/redteam/near/*.json). Nothing in the report is typed by hand.
//
//   node scripts/near/onchain-report.mjs
import fs from "node:fs";
import path from "node:path";

const DIR = "docs/redteam/near";
const read = (name) => {
  const file = path.join(DIR, name);
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : null;
};
const bypass = read("bypass-sandbox.json");
const revocation = read("revocation-sandbox.json");
const reconcile = read("reconcile-sandbox.json");
const anchor = read("anchor-sandbox.json");
const mutants = read("mutants.json");
const testnet = read("bypass-testnet.json");
const testnetVault = read("testnet-vault.json");
const anchorTestnet = read("anchor-testnet.json");

const t = (units) => (Number(BigInt(units) / BigInt(10_000)) / 100).toLocaleString("en-US", { minimumFractionDigits: 2 });
const by = (r) => (r.refusedBy === "protocol" ? "NEAR protocol (key permissions)" : r.refusedBy === "contract" ? "Vault contract" : "**NOT REFUSED**");
const out = [];
const line = (s = "") => out.push(s);

line("# On-chain red team (NEAR)");
line();
line("Generated by `node scripts/near/onchain-report.mjs` from the JSON evidence in");
line("[`docs/redteam/near/`](near/), which `scripts/near/evidence.sh` writes from the");
line("NEAR sandbox tests and the mutation checks. Do not edit by hand.");
line();
line("Networks: **sandbox** is a local NEAR node (neard 2.14.0) started by the tests;");
line("**testnet** is the public NEAR testnet. Test tokens have no value.");
line();
if (reconcile) {
  line(`Tested commit: \`${reconcile.commit}\`. Vault WASM sha256: \`${reconcile.wasmSha256.vault}\`; token WASM sha256: \`${reconcile.wasmSha256.token}\`.`);
  line();
}
if (testnetVault) {
  line(`The testnet vault \`${testnetVault.vault}\` runs code with sha256 \`${testnetVault.codeSha256}\` (on-chain code hash \`${testnetVault.codeHashBase58}\`, read ${testnetVault.upgradedAt}): ${testnetVault.matches ? "**the same build** the sandbox tests and mutation checks ran against" : "**a different build** from the tested one"}.`);
  line();
}

function bypassSection(run, title) {
  line(`## ${title}`);
  line();
  line("The agent's real function-call key, used directly against NEAR with Kinwarden's");
  line("app and safety gateway bypassed, as an attacker who owns the app server would.");
  line();
  const p = run.permissions;
  line(`**Key permissions** on \`${p.account}\`, read at block ${p.observedAt.blockHeight} (\`${p.observedAt.blockHash}\`):`);
  line();
  line("| Key | Kind | May call | Gas allowance | Note |");
  line("|---|---|---|---|---|");
  for (const k of [p.appKey, ...p.otherKeys].filter(Boolean)) {
    const calls = k.kind === "FunctionCall" ? `${(k.methods ?? []).join(", ")} on ${k.receiver}` : k.kind === "FullAccess" ? "anything" : "—";
    line(`| \`${k.publicKey}\` | ${k.kind} | ${calls} | ${k.allowanceNear ? `${k.allowanceNear} NEAR` : "—"} | ${k.note} |`);
  }
  line();
  line(p.paymentLimitsNote);
  line();
  line("| Attempt | Sent | Refused by | Reason |");
  line("|---|---|---|---|");
  for (const r of run.results) line(`| ${r.title} | \`${r.sent}\` | ${by(r)} | \`${r.reason}\` |`);
  line();
  line("| Balance | Before | After |");
  line("|---|---|---|");
  const rows = [
    ["Attacker (agent account) tUSDC", "agentTokens"],
    ["Vault tUSDC", "vaultTokens"],
    ["Family case balance", "caseBalance"],
    ["Family case reserved", "caseReserved"],
    ["Family case in flight", "caseInFlight"],
    ["Family case paid", "casePaid"],
  ];
  for (const [label, k] of rows) line(`| ${label} | ${t(run.before[k])} | ${t(run.after[k])} |`);
  line();
  line(run.held ? "**Held:** every attempt was refused and no balance changed." : "**NOT HELD:** an attempt was accepted or a balance changed.");
  line();
}

if (bypass) bypassSection(bypass, "Gateway bypass with the real agent key (sandbox)");
if (testnet) bypassSection(testnet, "Gateway bypass with the real agent key (testnet)");

if (revocation) {
  line("## Switching the agent off, then deleting its key (sandbox)");
  line();
  line(`After the family's \`revoke_agent\`, the case shows \`agent_enabled: ${revocation.case.agent_enabled}\` and \`reserved: ${revocation.case.reserved}\`; the pending proposal became \`${revocation.proposal.status}\` (\`${revocation.proposal.status_reason}\`).`);
  line("A new proposal is refused with `E_AGENT_DISABLED`, the agent cannot call `enable_agent` (NEAR: `MethodNameMismatch`), and once the account's setup key deletes the agent key, nothing it signs is accepted. Covered by `src/server/near/bypass.sandbox.ts`.");
  line();
}

if (reconcile) {
  line("## Balance reconciliation: a failed transfer and its retry (sandbox)");
  line();
  line(`Amount: ${t(reconcile.amountUnits)} tUSDC. The hospital's token account was removed before the first approval, so the vault's transfer failed; it registered again before the retry. Row 3 is read at the approval's own block: the state while the outcome is not yet known.`);
  line();
  line("| Step | Vault tUSDC | Hospital tUSDC | Case available | Reserved | In flight | Paid | 24 h budget used |");
  line("|---|---|---|---|---|---|---|---|");
  for (const r of reconcile.rows) line(`| ${r.step} | ${t(r.vaultTokens)} | ${t(r.hospitalTokens)} | ${t(r.caseAvailable)} | ${t(r.caseReserved)} | ${t(r.caseInFlight)} | ${t(r.casePaid)} | ${t(r.rolling24hCharged)} |`);
  line();
  line("A confirmed failure credits the hospital nothing and returns the amount and its 24-hour budget to the case once; a later sweep changes nothing; the retry pays exactly once. An outcome that stays unknown keeps the amount in flight: not spendable, not refunded and not resent.");
  line();
}

if (anchor) {
  line("## Activity-log anchor and tamper check (sandbox)");
  line();
  const a = anchor.anchor;
  line(`The app anchored log entry #${a.seq} (head \`${a.hash}\`) on \`${a.chain.contract}\` with the agent key: status \`${a.chain.status}\`, block ${a.chain.blockNumber}.`);
  line(`Check before any edit: \`ok: ${anchor.clean.ok}\`. After editing entry #${a.seq}: \`ok: ${anchor.tampered.ok}\`, "${anchor.tampered.reason}"`);
  line();
}

if (anchorTestnet) {
  line("## Activity-log anchor and tamper check (testnet)");
  line();
  const a = anchorTestnet.anchor;
  line(`Log entry #${a.seq} (head \`${a.hash}\`) anchored on \`${a.chain.contract}\`: [transaction](${a.chain.explorerUrl}), block ${a.chain.blockNumber}, label \`${anchorTestnet.clean.onChain.label}\`.`);
  line(`Check: \`ok: ${anchorTestnet.clean.ok}\`. After editing entry #${a.seq}: \`ok: ${anchorTestnet.tampered.ok}\`, "${anchorTestnet.tampered.reason}" After restoring the original text: \`ok: ${anchorTestnet.restored.ok}\`.`);
  line();
}

if (mutants) {
  line("## Targeted mutation checks");
  line();
  line(`Each mutation removes one hard check from the vault; \`${mutants.command}\` must fail with it applied (commit \`${mutants.commit}\`). This shows these tests cover these controls; it is not an audit or a coverage guarantee.`);
  line();
  line("| Control | Mutation caught | Failing tests |");
  line("|---|---|---|");
  for (const m of mutants.results) line(`| ${m.control} | ${m.killed ? "yes" : "**no**"} | ${m.failingTests.map((x) => `\`${x.replace(/^tests[a-z_]*::/, "")}\``).join(", ") || "—"} |`);
  line();
}

fs.writeFileSync("docs/redteam/ONCHAIN.md", out.join("\n"));
console.log(`Wrote docs/redteam/ONCHAIN.md (${out.length} lines)`);
